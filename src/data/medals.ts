import type { MedalRow } from "./types";

export type PlacedMedal = MedalRow & { place: number; total: number };

export function withPlaces(rows: MedalRow[]): PlacedMedal[] {
  const sorted = [...rows].sort(
    (a, b) => b.gold - a.gold || b.silver - a.silver || b.bronze - a.bronze || a.country.localeCompare(b.country),
  );
  let place = 0;
  return sorted.map((row, index) => {
    const prev = sorted[index - 1];
    if (!prev || prev.gold !== row.gold || prev.silver !== row.silver || prev.bronze !== row.bronze) {
      place = index + 1;
    }
    return { ...row, place, total: row.gold + row.silver + row.bronze };
  });
}

